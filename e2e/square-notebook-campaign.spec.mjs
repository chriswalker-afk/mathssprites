  await expect(page.locator("#notebook-playback-message")).toContainText("1 checked algebra step");
  await expect(page.locator("#notebook-playback-message")).toContainText("★★★");
  const data=await saved(page);
  expect(data.worlds.squares.stages.notebook.completed).toEqual(["square-a-01"]);
  expect(data.worlds.squares.stages.notebook.bestMoves["square-a-01"]).toBe(1);
