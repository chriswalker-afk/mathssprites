import {playCampaignLevel} from "./campaign-menu-helper.mjs";
import {openCampaignBoard,chooseCampaignWorld,chooseCampaignStage} from "./campaign-menu-helper.mjs";
import {test,expect} from "@playwright/test";
import {mkdirSync} from "node:fs";
const tile=(p,n)=>p.locator('.level-tile[data-level-id="square-a-'+String(n).padStart(2,"0")+'"]');
const lines=p=>p.locator("#notebook-lines li");
const input=p=>p.locator("#notebook-operation");
const result=p=>p.locator("#notebook-result-math");
const saved=p=>p.evaluate(()=>JSON.parse(localStorage.getItem("mathssprites.campaign.v2")));
async function board(p){
  await p.emulateMedia({reducedMotion:"reduce"});
  await p.addInitScript(()=>localStorage.setItem("mathssprites.motion-preference.v1","reduced"));
  await p.goto("/");
  await openCampaignBoard(p,"squares","notebook");
  await expect(p.locator("#site-levels")).toHaveAttribute("data-active-stage","notebook");
}
async function open(p,n){
  await tile(p,n).click();
  await expect(p.locator("#notebook-workspace")).toBeVisible();
  await expect(p.locator("#scene")).toBeHidden();
  await expect(p.locator("#notebook-stage-kicker")).toHaveText("WORLD 4 · STAGE 3 · LEVEL "+String(n).padStart(2,"0")+" / 16");
  await expect(p.locator("#square-inspect-toggle")).toBeHidden();
}
async function apply(p,text,expected){
  const count=await lines(p).count();
  await input(p).fill(text);
  await expect(result(p)).toHaveAttribute("data-state","valid");
  await expect(result(p)).toHaveAttribute("aria-label",expected);
  await expect(lines(p)).toHaveCount(count);
  await p.locator("#notebook-apply").click();
  await expect(lines(p)).toHaveCount(count+1);
  await expect(lines(p).last().locator(".notebook-line-equation")).toHaveAttribute("aria-label",expected);
  await expect(p.locator("#scene")).toBeHidden();
}
async function noCredit(p){
  const r=await saved(p);
  expect(r.worlds.squares.stages.notebook.completed).toEqual([]);
  expect(r.worlds.squares.stages.notebook.bestMoves).toEqual({});
}
async function shot(p,name){
  mkdirSync("artifacts",{recursive:true});
  await p.screenshot({path:"artifacts/square-notebook-"+name+".png",fullPage:true});
}
