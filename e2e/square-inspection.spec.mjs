  const geometry=await view(page).locator(".box-grid").evaluate(el=>{
    const r=el.getBoundingClientRect(),p=el.closest(".room-interior").getBoundingClientRect();
    return {square:Math.abs(r.width-r.height)<2,inside:r.left>=p.left-2&&r.right<=p.right+2&&r.top>=p.top-2&&r.bottom<=p.bottom+2};
  });
  expect(geometry).toEqual({square:true,inside:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await shot(page,"phone-fallback");
  await page.locator("#reset").click();
  await expect(view(page)).toBeHidden();
