import test from "node:test";
import assert from "node:assert/strict";
import {rational as q} from "../src/rational.mjs";
import {fractionTransform,fractionRoom} from "../src/fraction-engine.mjs";
import {fractionRefusalMarkup} from "../src/fraction-choreography.mjs";
import {weightPartition,polygonArea,weightInventoryMarkup} from "../src/fraction-weights.mjs";
import {spritePartition,spriteInventoryMarkup} from "../src/fraction-sprites.mjs";
test("unsupported cuts use equal-area original artwork only in an explicitly temporary trial",()=>{
  const room=fractionRoom({posX:q(3,4)}),action={op:"divide",factor:5};
  const failure=fractionTransform(room,action);
  assert.equal(failure.code,"unsupported-denominator");
  const html=fractionRefusalMarkup(failure,action,room);
  assert.match(html,/data-trial-denominator="20"/);
  assert.equal((html.match(/class="fs-piece"/g)||[]).length,20);
  assert.throws(()=>spritePartition(20));
  assert.throws(()=>spriteInventoryMarkup(q(3,20)));
  const sectors=spritePartition(20,{trial:true});
  assert.ok(sectors.every(p=>Math.abs(p.area-Math.PI*32**2/20)<1e-9));
  assert.throws(()=>spritePartition(121,{trial:true}));
  const weights=fractionRoom({posOne:q(1,8)});
  const weightAction={op:"divide",factor:3};
  const rejected=fractionTransform(weights,weightAction);
  assert.equal(rejected.denominator,24);
  const cut=fractionRefusalMarkup(rejected,weightAction,weights);
  assert.equal((cut.match(/class="fw-piece"/g)||[]).length,24);
  assert.throws(()=>weightPartition(24));
  assert.throws(()=>weightInventoryMarkup(q(1,24)));
  const slices=weightPartition(24,{trial:true});
  assert.ok(slices.every(p=>Math.abs(polygonArea(p.polygon)-polygonArea(slices[0].polygon))<1e-7));
  assert.deepEqual(room.posX,q(3,4));
});
test("overflow illustration is bounded, not a new committed inventory",()=>{
  const room=fractionRoom({posOne:48});
  const action={op:"multiply",factor:5};
  const rejected=fractionTransform(room,action);
  assert.equal(rejected.excess,192);
  const html=fractionRefusalMarkup(rejected,action,room);
  assert.match(html,/data-excess="192"/);
  assert.equal((html.match(/class="fb-spill-object"/g)||[]).length,5);
  assert.deepEqual(room.posOne,q(48));
  assert.equal(fractionRefusalMarkup({code:"missing"},action,room),"");
});
